let cachedSet: Set<string> | null = null;

function breachedSet(): Set<string> {
  cachedSet ??= new Set(BUNDLED_BREACHED_PASSWORDS.map((p) => p.toLowerCase()));
  return cachedSet;
}

/** Allows a deployment to supply a fuller corpus without touching callers. */
export function loadBreachedPasswords(passwords: Iterable<string>): void {
  cachedSet = new Set([...BUNDLED_BREACHED_PASSWORDS, ...passwords].map((p) => p.toLowerCase()));
}

export function isBreachedPassword(password: string): boolean {
  return breachedSet().has(password.toLowerCase());
}
